#!/usr/bin/env python3
"""Commit-message gate for sentrykit.

Enforces two things, mechanically, so they cannot be forgotten:

1. The header follows Conventional Commits: ``type(scope)?: subject``.
2. The message contains NO references to AI/agent tooling or generated-by attribution.

Wired as a ``commit-msg`` hook (see .pre-commit-config.yaml). Git passes the path to the
commit message file as ``argv[1]``. Exit non-zero to reject the commit.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

_CONVENTIONAL = re.compile(
    r"^(build|chore|ci|docs|feat|fix|perf|refactor|revert|style|test)(\([a-z0-9._/-]+\))?!?: .+"
)

# Case-insensitive substrings that must never appear anywhere in a commit message.
_FORBIDDEN: tuple[str, ...] = (
    "claude",
    "anthropic",
    "copilot",
    "cursor",
    "chatgpt",
    "openai",
    "gpt-",
    "co-authored-by: claude",
    "generated with",
    "generated by",
    "ai-assisted",
    "ai assisted",
    "as an ai",
    "language model",
    "\U0001f916",  # robot emoji
)


def check(message: str) -> list[str]:
    lines = [ln for ln in message.splitlines() if not ln.lstrip().startswith("#")]
    header = next((ln for ln in lines if ln.strip()), "")
    body = "\n".join(lines).strip()

    problems: list[str] = []
    if not _CONVENTIONAL.match(header):
        problems.append(
            "header must follow Conventional Commits '<type>(<scope>): <subject>' "
            "(types: build chore ci docs feat fix perf refactor revert style test)"
        )
    lowered = body.lower()
    hits = sorted({t for t in _FORBIDDEN if t in lowered})
    if hits:
        problems.append(
            "disallowed tooling/attribution reference(s): " + ", ".join(map(repr, hits))
        )
    return problems


def main(argv: list[str]) -> int:
    if len(argv) < 2:
        print("commit-msg hook: no message file provided", file=sys.stderr)
        return 1
    message = Path(argv[1]).read_text(encoding="utf-8")
    problems = check(message)
    if problems:
        print("COMMIT REJECTED:", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        print("\nWrite the message as a human engineer would.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
