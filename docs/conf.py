"""Sphinx configuration for the sentrykit documentation.

The repository is private, so there is nowhere to host a site: the documentation ships as
release assets instead. One source tree therefore has to feed three builders — ``html`` for
people, ``rinoh`` for the PDF, and ``markdown`` as the intermediate that
``scripts/build_llms_txt.py`` flattens into ``llms.txt`` and ``llms-full.txt``. Everything
below is chosen to keep those three in agreement.

The pages under ``docs/`` are plain GitHub-flavoured Markdown, read by MyST-Parser unchanged.
The API reference is generated by ``autodoc`` from the docstrings that already exist in
``src/sentrykit`` — and those are written in the same Markdown the pages are, so
:func:`_markdown_to_rst` normalises the handful of constructs reStructuredText spells
differently before docutils ever sees them. Nothing here is written by hand twice.

``sentrykit`` is installed editable into every pixi environment, so it imports without any
``sys.path`` surgery — and it has to, because ``autodoc`` imports it regardless.
"""

