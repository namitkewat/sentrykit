# --- Cedar syntax highlighting ----------------------------------------------


class CedarLexer(RegexLexer):
    """Highlight Cedar policy text.

    Pygments ships no Cedar lexer, and a fenced block tagged `cedar` without one is a warning
    that `-W` turns into a failed build — so the choice is between this and rendering the most
    important code on the most important page as undifferentiated grey. The grammar covered is
    the one the pages use: `permit` / `forbid` with their conditions, `Type::"id"` entity
    literals, `//` comments and `@id(...)` annotations.
    """

    name = "Cedar"
    aliases: ClassVar[list[str]] = ["cedar"]
    filenames: ClassVar[list[str]] = ["*.cedar"]

    tokens: ClassVar[dict[str, list[Any]]] = {
        "root": [
            (r"//[^\n]*", Comment.Single),
            (r"\s+", Whitespace),
            (r"@[A-Za-z_][A-Za-z0-9_]*", Name.Decorator),
            (r'"(?:\\.|[^"\\])*"', String.Double),
            (
                words(
                    (
                        "permit",
                        "forbid",
                        "when",
                        "unless",
                        "if",
                        "then",
                        "else",
                        "has",
                        "like",
                        "is",
                        "in",
                    ),
                    suffix=r"\b",
                ),
                Keyword,
            ),
            (words(("principal", "action", "resource", "context"), suffix=r"\b"), Name.Builtin),
            (words(("true", "false"), suffix=r"\b"), Keyword.Constant),
            (r"[A-Z][A-Za-z0-9_]*(?=\s*::)", Name.Class),
            (r"\d+", Number.Integer),
            (r"==|!=|<=|>=|&&|\|\||::|[<>!+\-*=]", Operator),
            (r"[{}()\[\];,.:]", Punctuation),
            (r"[A-Za-z_][A-Za-z0-9_]*", Name),
        ]
    }


# --- Markdown docstrings ----------------------------------------------------
# Every docstring in `src/sentrykit` is written in the same Markdown the pages are, because
# that is what the people reading the source expect. docutils reads reStructuredText, where a
# ``` fence is an unterminated inline literal and an indented line after a paragraph is an
# error — dozens of warnings, and `-W` fails on the first. Rather than rewrite three hundred
# kilobytes of docstrings into a markup their readers do not use, the four constructs that
# actually differ are translated here, on the way in.

_HEADING: Final = re.compile(r"^(#{1,6})\s+(.*)$")
"""A Markdown ATX heading. A docstring cannot open a section — it is already inside one — so
these become bold lead-ins rather than titles."""

_FENCE: Final = re.compile(r"^```+\s*([A-Za-z0-9_+-]*)\s*$")
"""A fenced code block, opening or closing. The capture is the language, if it carries one."""

_TABLE_RULE: Final = re.compile(r"^\|(?:\s*:?-{2,}:?\s*\|)+$")
"""The dashed row under a pipe-table header, which is what identifies the block as a table."""

_DEFAULT_LANGUAGE: Final = "text"
"""Language for a fence that names none. `text` highlights nothing, which is correct for the
sequence sketches and shell transcripts that go unlabelled."""


def _split_row(line: str) -> list[str]:
    """Split one pipe-table row into its cells.

    Args:
        line: A single line beginning and ending with `|`.

    Returns:
        The cell texts, stripped, without the empty leading and trailing fields.
    """
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def _emit_table(rows: list[list[str]], indent: str, out: list[str]) -> None:
    """Append one pipe table to `out` as a reStructuredText `list-table`.

    A `list-table` rather than a drawn grid because the cells carry inline markup of their
    own, and a grid would need its column widths to survive that markup being rendered.

    Args:
        rows: Header row first, then the body rows.
        indent: Leading whitespace to reproduce on every emitted line.
        out: The line list being built, appended to in place.
    """
    width = max(len(row) for row in rows)
    out.extend(
        (
            "",
            f"{indent}.. list-table::",
            f"{indent}   :header-rows: 1",
            "",
        )
    )
    for row in rows:
        cells = [*row, *[""] * (width - len(row))]
        out.append(f"{indent}   * - {cells[0]}")
        out.extend(f"{indent}     - {cell}" for cell in cells[1:])
    out.append("")


def _markdown_to_rst(lines: list[str]) -> list[str]:
    """Translate the Markdown constructs a docstring uses into reStructuredText.

    Handles fenced code blocks, ATX headings, blockquotes and pipe tables. Everything else —
    emphasis, inline code, bullet and numbered lists, and the Sphinx roles the docstrings
    already carry — means the same thing in both markups and is passed through untouched.

    Args:
        lines: The docstring, one entry per line, without trailing newlines.

    Returns:
        A new list of lines, safe to hand to docutils.
    """
    out: list[str] = []
    fence_indent: str | None = None
    quoting = False
    table: list[list[str]] = []
    table_indent = ""

    for raw in lines:
        stripped = raw.strip()
        indent = raw[: len(raw) - len(raw.lstrip())]

        if fence_indent is not None:
            if _FENCE.match(stripped):
                fence_indent = None
                out.append("")
            else:
                out.append(f"   {raw}" if stripped else "")
            continue

        # A pipe table is only a table once its dashed rule has been seen; a lone `|` line is
        # ordinary prose and is left where it was written.
        if table:
            if stripped.startswith("|"):
                table.append(_split_row(stripped))
                continue
            _emit_table(table, table_indent, out)
            table = []
        if stripped.startswith("|") and out and _TABLE_RULE.match(stripped):
            table = [_split_row(out.pop().strip())]
            table_indent = indent
            continue

        if quoting and not stripped.startswith(">"):
            quoting = False
            out.append("")

        fence = _FENCE.match(stripped)
        if fence:
            if out and out[-1].strip():
                out.append("")
            out.append(f"{indent}.. code-block:: {fence.group(1) or _DEFAULT_LANGUAGE}")
            out.append("")
            fence_indent = indent
            continue

        heading = _HEADING.match(stripped)
        if heading:
            if out and out[-1].strip():
                out.append("")
            out.append(f"{indent}**{heading.group(2).strip()}**")
            out.append("")
            continue

        if stripped.startswith(">"):
            if not quoting:
                if out and out[-1].strip():
                    out.append("")
                quoting = True
            out.append(f"{indent}   {stripped.lstrip('>').strip()}")
            continue

        out.append(raw)

    if table:
        _emit_table(table, table_indent, out)
    if fence_indent is not None:
        out.append("")
    return out


def _process_docstring(
    app: Sphinx,
    what: str,
    name: str,
    obj: object,
    options: object,
    lines: list[str],
) -> None:
    """Rewrite one docstring in place, before napoleon parses its sections.

    Args:
        app: The Sphinx application. Unused.
        what: The kind of object being documented. Unused.
        name: The object's fully qualified name. Unused.
        obj: The object itself. Unused.
        options: The directive options. Unused.
        lines: The docstring's lines, replaced in place — which is how this event hands work
            back to autodoc.
    """
    lines[:] = _markdown_to_rst(lines)


def setup(app: Sphinx) -> dict[str, Any]:
    """Register the Cedar lexer and the Markdown-docstring translation.

    Args:
        app: The Sphinx application.

    Returns:
        Extension metadata. Nothing here holds state across documents, so every builder may
        read and write in parallel.
    """
    app.add_lexer("cedar", CedarLexer)
    # Priority 400 puts this ahead of napoleon's default 500, so napoleon parses `Args:` and
    # `Returns:` out of text that is already reStructuredText.
    app.connect("autodoc-process-docstring", _process_docstring, priority=400)
    return {"parallel_read_safe": True, "parallel_write_safe": True}
